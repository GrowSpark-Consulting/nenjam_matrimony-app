// Backend-only pairwise psychology compatibility result shapes. Deliberately
// separate from anything CompatibilityService/Discover reads — nothing here
// is wired into matching yet.

export type PsychologyCompatibilityStatus =
  | 'COMPLETE'
  | 'USER_A_INCOMPLETE'
  | 'USER_B_INCOMPLETE'
  | 'BOTH_INCOMPLETE'
  | 'NO_ACTIVE_QUIZ'
  | 'UNSUPPORTED_QUIZ_VERSION';

export type PsychologyFlagSeverity = 'soft' | 'medium' | 'high' | 'hard';

export interface QuestionCompatibilityBreakdown {
  questionId: string;
  dimension: string;
  score: number; // 0-100, from the approved static matrix
  userASelectedKey: string;
  userBSelectedKey: string;
}

export interface PsychologyCompatibilityFlag {
  /** null for an informational flag that doesn't anchor to one question (the Q8-D/Q3 note). */
  questionId: string | null;
  dimension: string | null;
  /**
   * Absent (undefined) for a purely informational/discussion note that is
   * NOT a compatibility-risk severity and must never be read as one — today
   * that is exactly and only the Q8-D/Q3 cross-check (identifiable either by
   * `severity === undefined` or by `source === 'informational'`). Every
   * pairRule-derived flag (including one escalated by the Q10<->Q9 rule)
   * always carries a real severity from that question's own `pairRules`.
   */
  severity?: PsychologyFlagSeverity;
  message: string;
  /** 'pairRule' = read live from that question's QuizQuestion.pairRules, unchanged (severity always present).
   *  'informational' = a discussion-only cross-reference generated by a second-pass rule (currently just the
   *  Q8-D<->Q3 note) — never a compatibility-risk severity, never a dealbreaker, never affects the score. */
  source: 'pairRule' | 'informational';
}

export interface PsychologyCompatibilityResult {
  status: PsychologyCompatibilityStatus;
  quizId: string | null;
  /** null unless status === 'COMPLETE'. */
  overallScore: number | null;
  /** true when Q9's HARD_AXIS dealbreaker pair forced overallScore down to the <=40 ceiling. */
  ceilingApplied: boolean;
  breakdown: QuestionCompatibilityBreakdown[];
  flags: PsychologyCompatibilityFlag[];
  /** Question ids excluded from the average because one side's answer for that
   *  question was missing from an otherwise-COMPLETE pair of responses. Should
   *  be empty in practice (submit-time validation requires all 10 answers),
   *  present only for defensive handling of malformed stored data. */
  skippedQuestionIds: string[];
}
